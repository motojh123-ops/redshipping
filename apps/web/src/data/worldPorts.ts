/**
 * Returns all ports as a flat list
 */
export function getAllPortsList(): PortDefinition[] {
  return Object.values(WORLD_PORTS);
}

/**
 * Returns ports organized by geographic region for grouped dropdowns
 */
export function getPortsGroupedByRegion(): PortRegionGroup[] {
  const allPorts = getAllPortsList();
  return PORT_REGIONS_ORDER.map((reg) => {
    const ports = allPorts.filter((p) => (p.region || 'Europe') === reg.key);
    return {
      regionKey: reg.key,
      regionNameAr: reg.nameAr,
      regionNameEn: reg.nameEn,
      flag: reg.flag,
      ports,
    };
  }).filter((group) => group.ports.length > 0);
}

/**
 * Fast search ports by code, English name, Arabic name, country, or city
 */
export function searchPorts(query: string, options?: { region?: string; countryCode?: string; portType?: string }): PortDefinition[] {
  let list = getAllPortsList();

  if (options?.region && options.region !== 'all') {
    list = list.filter((p) => p.region === options.region);
  }

  if (options?.countryCode && options.countryCode !== 'all') {
    list = list.filter((p) => p.countryCode.toUpperCase() === options.countryCode!.toUpperCase());
  }

  if (options?.portType && options.portType !== 'all') {
    list = list.filter((p) => (p.portType || (p.isDryPort ? 'dry' : 'sea')) === options.portType);
  }

  if (!query || !query.trim()) return list;

  const q = query.trim().toLowerCase();
  return list.filter((p) =>
    p.unlocode.toLowerCase().includes(q) ||
    p.name.toLowerCase().includes(q) ||
    p.nameAr.toLowerCase().includes(q) ||
    p.country.toLowerCase().includes(q) ||
    (p.city && p.city.toLowerCase().includes(q))
  );
}

/**
 * Lookup port by UN/LOCODE with fallback
 */
export function getPortByCode(code?: string): PortDefinition | undefined {
  if (!code) return undefined;
  const upper = code.trim().toUpperCase();
  return WORLD_PORTS[upper];
}
